    "active AND kind='agent')\n"
    "  OR NOT EXISTS(SELECT 1 FROM principals WHERE tenant_id=r.tenant_id AND id=r.requester_id "
    "AND active AND kind='human')\n"
    "  OR (r.category_id IS NOT NULL AND category_access(r.tenant_id,r.category_id) IS DISTINCT "
    "FROM true) THEN\n"
    "  RAISE EXCEPTION 'Read provenance requires current active Run and principals' USING "
    "ERRCODE='23514';\n"
    " END IF;\n"
    " SELECT * INTO m FROM agent_tool_calls WHERE tenant_id=r.tenant_id AND run_id=r.id AND "
    "id=(b->>'model_call_id')::uuid;\n"
    " IF m.id IS NULL OR m.id=NEW.id OR m.tool<>'model' OR m.state<>'completed'\n"
    "  OR m.error_code IS NOT NULL OR m.receipt_id IS NOT NULL\n"
    "  OR m.execution_binding->>'kind' IS DISTINCT FROM 'model'\n"
    "  OR m.execution_binding->>'isolation' IS DISTINCT FROM isolation\n"
