    "CREATE OR REPLACE FUNCTION public.assert_quality_change_receipt(tid uuid, pid uuid, sid uuid, "
    "rev integer, op_name text, subject_name text, actor uuid, audience text)\n"
    " RETURNS void\n"
    " LANGUAGE plpgsql\n"
    "AS $function$\n"
    "DECLARE receipt action_receipts%ROWTYPE; expected_event text;\n"
    "BEGIN\n"
    "  SELECT * INTO receipt FROM action_receipts WHERE tenant_id=tid AND product_id=pid\n"
    "    AND subject_id=sid AND subject_revision=rev AND operation=op_name\n"
    "    AND subject_type=subject_name AND actor_id=actor AND requester_id=actor AND run_id IS NULL\n"
    "    AND visibility=audience;\n"
    "  expected_event := CASE op_name\n"
    "    WHEN 'quality.issue.create' THEN 'issue.created'\n"
    "    WHEN 'quality.issue.merge' THEN 'issues.merged'\n"
    "    WHEN 'quality.issue.triage' THEN 'issue.triaged'\n"
    "    WHEN 'quality.issue.containment.record' THEN 'issue.contained'\n"
    "    WHEN 'quality.capa.draft' THEN 'capa.drafted'\n"
    "    WHEN 'quality.policy.import' THEN 'quality.policy_imported'\n"
    "    WHEN 'change.request.create' THEN 'change.requested'\n"
    "    WHEN 'change.impact.compute' THEN 'change.impact_created'\n"
    "    WHEN 'change.order.prepare' THEN 'change.order_prepared'\n"
    "    WHEN 'change.order.approve' THEN 'change.approved'\n"
    "    WHEN 'change.implementation.record' THEN 'change.implementation_recorded'\n"
    "    WHEN 'change.effectivity.record' THEN 'change.effectivity_recorded'\n"
    "    WHEN 'change.verification.record' THEN 'change.verification_recorded'\n"
    "    WHEN 'change.close' THEN 'change.closed'\n"
    "    WHEN 'quality.issue.root_cause.decide' THEN 'issue.root_cause_decided'\n"
    "    WHEN 'quality.capa.actions.complete' THEN 'capa.actions_completed'\n"
    "    WHEN 'quality.capa.followup.link' THEN 'capa.followup_linked'\n"
    "    WHEN 'quality.capa.verification.rule.import' THEN 'CapaVerificationRulePublished'\n"
    "    WHEN 'quality.capa.observation.record' THEN 'CapaObservationRecorded'\n"
    "    WHEN 'quality.capa.verification.review' THEN 'CapaVerificationReviewed'\n"
    "    WHEN 'quality.capa.verification.candidate.record' THEN 'CapaVerificationCandidateRecorded' "
    "END;\n"
    "  IF receipt.id IS NULL OR expected_event IS NULL\n"
    "    OR (SELECT count(*) FROM action_receipts WHERE tenant_id=tid AND product_id=pid\n"
    "      AND subject_id=sid AND subject_revision=rev AND operation=op_name)<>1\n"
    "    OR (SELECT count(*) FROM audit_entries WHERE tenant_id=tid AND receipt_id=receipt.id)<>1\n"
    "    OR NOT EXISTS (SELECT 1 FROM audit_entries WHERE tenant_id=tid AND receipt_id=receipt.id\n"
