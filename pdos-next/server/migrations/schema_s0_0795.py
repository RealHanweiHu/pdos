    " END IF;\n"
    " FOR time_value IN SELECT value FROM "
    "jsonb_array_elements(jsonb_build_array(v.body->'actual_start',v.body->'submission'->'time',v.body->'review'->'time')) "
    "WHERE value<>'null'::jsonb LOOP\n"
    "  IF (time_value->>'actual_at')::timestamptz>(time_value->>'recorded_at')::timestamptz\n"
    "   OR (time_value->>'recorded_at')::timestamptz>v.created_at THEN\n"
    "   RAISE EXCEPTION 'Task actual time cannot be in the future of its recording' USING "
    "ERRCODE='23514'; END IF;\n"
    " END LOOP;\n"
    " IF "
    "(v.body->'actual_start'->>'actual_at')::timestamptz>(v.body->'submission'->'time'->>'actual_at')::timestamptz\n"
    "  OR "
    "(v.body->'submission'->'time'->>'actual_at')::timestamptz>(v.body->'review'->'time'->>'actual_at')::timestamptz "
    "THEN\n"
    "  RAISE EXCEPTION 'Task actual start submission and review must be monotone' USING "
    "ERRCODE='23514'; END IF;\n"
    "END;\n"
