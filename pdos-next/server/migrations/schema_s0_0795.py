    "CREATE OR REPLACE FUNCTION public.assert_work_task(t uuid, target uuid)\n"
    " RETURNS void\n"
    " LANGUAGE plpgsql\n"
    " SECURITY DEFINER\n"
    " SET search_path TO 'pg_catalog', 'public', 'pg_temp'\n"
    "AS $function$\n"
    "\n"
    "DECLARE v public.work_task_versions; prior public.work_task_versions; cur "
    "public.work_task_currents;\n"
    " vx xid; cx xid; allowed text[]; required_key text; time_value jsonb;\n"
    "BEGIN\n"
    " SELECT * INTO STRICT v FROM public.work_task_versions WHERE tenant_id=t AND id=target;\n"
    " SELECT xmin INTO vx FROM public.work_task_versions WHERE tenant_id=t AND id=target;\n"
    " SELECT * INTO STRICT cur FROM public.work_task_currents WHERE tenant_id=t AND "
    "product_id=v.product_id AND task_id=v.task_id;\n"
    " SELECT xmin INTO cx FROM public.work_task_currents WHERE tenant_id=t AND id=cur.id;\n"
    " PERFORM public.assert_work_management_write(t,target,'work_task');\n"
    " IF vx IS DISTINCT FROM cx OR "
    "ROW(cur.category_id,cur.product_id,cur.project_id,cur.owner_id,cur.visibility,cur.task_id,cur.version_id,cur.revision,cur.state)\n"
    "  IS DISTINCT FROM "
    "ROW(v.category_id,v.product_id,v.project_id,v.owner_id,v.visibility,v.task_id,v.id,v.revision,v.state)\n"
    "  OR v.body->>'task_id' IS DISTINCT FROM v.task_id::text OR v.body->>'revision' IS DISTINCT FROM "
    "v.revision::text OR v.body->>'state' IS DISTINCT FROM v.state THEN\n"
    "  RAISE EXCEPTION 'Task fact needs its exact same-transaction Current' USING ERRCODE='23514'; "
    "END IF;\n"
    " IF v.revision=1 THEN\n"
    "  IF v.body->>'title' IS DISTINCT FROM v.command->'envelope'->'payload'->>'title' OR "
    "v.body->>'goal' IS DISTINCT FROM v.command->'envelope'->'payload'->>'goal'\n"
    "   OR v.body->'outcomes' IS DISTINCT FROM v.command->'envelope'->'payload'->'outcomes'\n"
    "   OR v.body->'plan_task' IS DISTINCT FROM v.command->'envelope'->'payload'->'plan_task'\n"
    "   OR v.body->'assignee_id' IS DISTINCT FROM 'null'::jsonb OR v.body->'recipient_id' IS DISTINCT "
    "FROM 'null'::jsonb\n"
    "   OR v.body->'actual_start' IS DISTINCT FROM 'null'::jsonb OR v.body->'submission' IS DISTINCT "
    "FROM 'null'::jsonb OR v.body->'review' IS DISTINCT FROM 'null'::jsonb THEN\n"
    "   RAISE EXCEPTION 'Created task records proposed work only' USING ERRCODE='23514'; END IF;\n"
    " ELSE\n"
    "  SELECT * INTO STRICT prior FROM public.work_task_versions WHERE tenant_id=t AND "
    "id=v.previous_id;\n"
    "  IF v.command->'envelope'->'payload'->'task' IS DISTINCT FROM "
    "jsonb_build_object('id',v.task_id,'revision',prior.revision) THEN\n"
    "   RAISE EXCEPTION 'Task action requires its exact stable task revision' USING ERRCODE='23514'; "
    "END IF;\n"
    "  allowed=ARRAY['revision','state'];\n"
    "  IF v.action='assign' AND prior.state IN ('proposed','assigned') AND v.state='assigned' AND "
    "v.actor_id=v.owner_id THEN\n"
    "   allowed=allowed||ARRAY['assignee_id','recipient_id'];\n"
    "   IF v.body->'assignee_id' IS DISTINCT FROM v.command->'envelope'->'payload'->'assignee_id' OR "
    "v.body->'recipient_id' IS DISTINCT FROM v.command->'envelope'->'payload'->'recipient_id' THEN "
    "RAISE EXCEPTION 'Task assignment mismatch' USING ERRCODE='23514'; END IF;\n"
    "  ELSIF v.action='accept' AND prior.state='assigned' AND v.state='accepted' AND "
    "prior.body->>'assignee_id'=v.actor_id::text THEN NULL;\n"
    "  ELSIF v.action='start' AND prior.state='accepted' AND v.state='in_progress' AND "
    "prior.body->>'assignee_id'=v.actor_id::text THEN\n"
    "   allowed=allowed||ARRAY['actual_start'];\n"
    "  ELSIF v.action='submit' AND prior.state='in_progress' AND v.state='submitted' AND "
    "prior.body->>'assignee_id'=v.actor_id::text THEN\n"
    "   allowed=allowed||ARRAY['submission','review'];\n"
    "  ELSIF v.action='review' AND prior.state='submitted' AND "
    "prior.body->>'recipient_id'=v.actor_id::text\n"
    "   AND ((v.body->'review'->>'decision'='accepted' AND v.state='completed') OR "
    "(v.body->'review'->>'decision'='returned' AND v.state='in_progress')) THEN\n"
    "   allowed=allowed||ARRAY['review'];\n"
    "   IF v.state='completed' THEN\n"
    "    FOR required_key IN SELECT value->>'key' FROM jsonb_array_elements(v.body->'outcomes') WHERE "
    "value->'required'='true'::jsonb LOOP\n"
    "     IF NOT EXISTS(SELECT 1 FROM jsonb_array_elements(v.body->'submission'->'results') x WHERE "
    "x->>'key'=required_key AND x->>'status'='present')\n"
    "      OR NOT EXISTS(SELECT 1 FROM jsonb_array_elements(v.body->'review'->'checks') x WHERE "
    "x->>'key'=required_key AND x->>'decision'='accepted') THEN\n"
    "      RAISE EXCEPTION 'Required task outcome not accepted' USING ERRCODE='23514'; END IF;\n"
    "    END LOOP;\n"
    "   END IF;\n"
    "  ELSE RAISE EXCEPTION 'Invalid task transition or actual actor' USING ERRCODE='23514'; END IF;\n"
    "  IF (v.body-allowed) IS DISTINCT FROM (prior.body-allowed) THEN RAISE EXCEPTION 'Task action "
