async function submitEvaluation() {
  fireEvent.click(await screen.findByRole("button", { name: "读取当前租户模型" }));
  await screen.findByText("openai · synthetic-model");
  const bytes = new TextEncoder().encode(JSON.stringify(suite));
  const file = new File([bytes], "human-reference.json", { type: "application/json" });
  Object.defineProperty(file, "arrayBuffer", { value: async () => bytes.buffer });
  fireEvent.change(screen.getByLabelText("人工参考文件"), { target: { files: [file] } });
  await screen.findByText(/human-reference.json ·/);
  fireEvent.change(screen.getByLabelText("已核对的模型配置摘要"), { target: { value: "c".repeat(64) } });
  fireEvent.change(screen.getByLabelText("评测编号（继续已有评测时填写）"), { target: { value: run } });
  fireEvent.click(screen.getByRole("button", { name: "核对全部样例来源" }));
  await screen.findByText(/当前来源与执行版本相符/);
  fireEvent.click(screen.getByRole("button", { name: "提交影子评测" }));
}
const writes = () => fetcher.mock.calls.filter(([input]) => String(input).endsWith("/evaluation/suite"));
it.each([503, 408])("keeps actual workspace navigation and original evaluation locked after uncertain %s until the same request returns", async status => {
  writeStatus = status;
  render(<ProductWorkspace/>);
  await submitEvaluation();
  await screen.findByText("原评测回执未确认");
  expect(screen.getByRole("button", { name: /^市场空间$/ })).toBeDisabled();
  expect(screen.getByRole("button", { name: "刷新工作与来源" })).toBeDisabled();
  expect(screen.getByRole("button", { name: "准备另一轮评测" })).toBeDisabled();
  for (const tab of screen.getAllByRole("tab")) expect(tab).toBeDisabled();
  expect(screen.getByRole("button", { name: "重试原评测请求" })).toBeEnabled();
  const originalUrl = location.search;
  fireEvent.click(screen.getByRole("tab", { name: "PRD·Spec" }));
  fireEvent.click(screen.getByRole("button", { name: /^市场空间$/ }));
  fireEvent.click(screen.getByRole("button", { name: "准备另一轮评测" }));
  expect(location.search).toBe(originalUrl);
  expect(writes()).toHaveLength(1);
  writeStatus = 200;
  fireEvent.click(screen.getByRole("button", { name: "重试原评测请求" }));
  await screen.findByText("样例比对通过，仍待人工复核与独立证明。");
  expect(writes()).toHaveLength(2);
  expect(writes()[0][1]?.body).toBe(writes()[1][1]?.body);
  expect(JSON.parse(String(writes()[1][1]?.body)).evaluation_id).toBe(run);
  await waitFor(() => expect(screen.getByRole("button", { name: /^市场空间$/ })).toBeEnabled());
  expect(screen.getByRole("tab", { name: "PRD·Spec" })).toBeEnabled();
  expect(screen.getByRole("button", { name: "准备另一轮评测" })).toBeEnabled();
});
it("releases navigation after a definite source refusal while preserving the batch identity", async () => {
  writeStatus = 409;
  render(<ProductWorkspace/>);
  await submitEvaluation();
  await screen.findByText("原来源已漂移");
  await waitFor(() => expect(screen.getByRole("button", { name: /^市场空间$/ })).toBeEnabled());
  expect(screen.getByText(`本次评测编号：${run}`)).toBeInTheDocument();
  expect(screen.getByRole("button", { name: "准备另一轮评测" })).toBeEnabled();
  expect(writes()).toHaveLength(1);
  expect(screen.queryByText(/未产生运行|未调用模型/)).not.toBeInTheDocument();
});
it.each([401, 403])("clears the actual parent on evaluation %s and restores only on explicit authorized retry", async status => {
  writeStatus = status;
  render(<ProductWorkspace/>);
  await submitEvaluation();
  await screen.findByRole("button", { name: "重试" });
  expect(screen.queryByRole("tablist")).not.toBeInTheDocument();
  expect(screen.queryByLabelText("人工参考文件")).not.toBeInTheDocument();
  expect(screen.queryByText(/human-reference.json ·/)).not.toBeInTheDocument();
  expect(screen.queryByText(`本次评测编号：${run}`)).not.toBeInTheDocument();
  expect(screen.getByRole("button", { name: /^市场空间$/ })).toBeEnabled();
  writeStatus = 200;
  fireEvent.click(screen.getByRole("button", { name: "重试" }));
  await screen.findByLabelText("人工参考文件");
  expect(screen.getByLabelText("已核对的模型配置摘要")).toHaveValue("");
  expect(screen.getByLabelText("评测编号（继续已有评测时填写）")).toHaveValue("");
  expect(screen.getByLabelText("原运行编号")).toHaveValue("");
  expect(writes()).toHaveLength(1);
});
it("rejects a late full-workspace read after evaluation authority is revoked", async () => {
  render(<ProductWorkspace/>);
  await screen.findByLabelText("人工参考文件");
  pendingWorkspace = new Promise(resolve => { finishWorkspace = resolve; });
  fireEvent.click(screen.getByRole("button", { name: "刷新工作与来源" }));
  writeStatus = 403;
  await submitEvaluation();
  await screen.findByRole("button", { name: "重试" });
  await act(async () => { finishWorkspace(Response.json(workspace)); await Promise.resolve(); });
  expect(screen.queryByRole("tablist")).not.toBeInTheDocument();
  expect(screen.queryByLabelText("人工参考文件")).not.toBeInTheDocument();
});
